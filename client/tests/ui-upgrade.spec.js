import {test,expect} from '@playwright/test'
test('login carousel, password reset, themes, safe area and contact scrolling',async({page,request},info)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.emulateMedia({colorScheme:'dark'})
  await page.goto('/login')
  await expect(page.locator('html')).toHaveClass('dark')
  await expect(page.getByRole('heading',{name:'欢迎使用数科2441智能班务系统'})).toBeVisible()
  await expect(page.getByRole('button',{name:'查看第 3 张照片'})).toBeVisible()
  await page.getByRole('button',{name:'查看第 2 张照片'}).click()
  await expect(page.locator('.photo-frame img')).toHaveAttribute('src','/login-slides/2.webp')
  await expect.poll(()=>page.locator('.photo-frame img').evaluate(el=>el.complete&&el.naturalWidth>0)).toBeTruthy()
  await page.screenshot({path:`test-results/${info.project.name}-login-dark.png`,fullPage:true})
  await page.getByLabel('外观主题').selectOption('light')
  await page.reload();await expect(page.locator('html')).not.toHaveClass('dark')
  await page.screenshot({path:`test-results/${info.project.name}-login-light.png`,fullPage:true})
  const admin=(await (await request.post('/api/login',{data:{username:'A',password:'PreviewOnly123!'}})).json())
  const headers={Authorization:`Bearer ${admin.access_token}`}
  const username=`reset-ui-${info.project.name}`
  const created=await request.post('/api/users',{headers,data:{username,real_name:'界面重置测试',student_id:`ui-${info.project.name}`,password:'InitialOnly123!'}})
  expect(created.ok()).toBeTruthy();const user=await created.json()
  const code=(await(await request.post(`/api/users/${user.id}/reset-code`,{headers})).json()).code
  try{
    await page.getByRole('button',{name:'忘记密码？'}).click()
    const dialog=page.getByRole('dialog')
    const inputs=dialog.locator('input')
    await inputs.nth(0).fill(user.student_id);await inputs.nth(1).fill(code);await inputs.nth(2).fill('ChangedOnly123!');await inputs.nth(3).fill('ChangedOnly123!')
    await dialog.getByRole('button',{name:'重置并返回登录'}).click();await expect(dialog).toBeHidden()
    await page.getByRole('textbox',{name:'密码',exact:true}).fill('ChangedOnly123!')
    await page.getByRole('button',{name:'登 录'}).click();await expect(page).toHaveURL(/dashboard/)
  }finally{await request.delete(`/api/users/${user.id}`,{headers})}
  await page.addInitScript(({token,user})=>{localStorage.setItem('token',token);localStorage.setItem('user',JSON.stringify(user));localStorage.setItem('login_time',String(Date.now()))},{token:admin.access_token,user:admin.user})
  await page.route('**/api/class-committee',route=>route.fulfill({json:Array.from({length:25},(_,i)=>({id:i,real_name:`测试班委${i+1}`,class_position:'班级事务',phone:'123456789',qq_number:'10000'}))}))
  await page.goto('/dashboard')
  await page.evaluate(()=>document.documentElement.style.setProperty('--safe-area-inset-top','28px'))
  expect(await page.locator('.admin-header').evaluate(el=>parseFloat(getComputedStyle(el).paddingTop))).toBe(28)
  await page.getByLabel('外观主题').selectOption('dark')
  await page.getByRole('button',{name:'班委联系方式',exact:true}).click()
  const panel=page.getByRole('region',{name:'班委联系信息'})
  await expect(panel).toBeVisible()
  expect(await panel.evaluate(el=>{const e=new Event('touchstart',{bubbles:true,cancelable:true});el.dispatchEvent(e);return e.defaultPrevented})).toBeFalsy()
  const box=await panel.boundingBox()
  if(info.project.name==='phone'){
    const cdp=await page.context().newCDPSession(page)
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+box.width/2,y:box.y+box.height-30}]})
    for(let step=1;step<=8;step++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:box.x+box.width/2,y:box.y+box.height-30-step*25}]})
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  }else{await panel.hover();await page.mouse.wheel(0,350)}
  await expect.poll(()=>panel.evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
  await page.screenshot({path:`test-results/${info.project.name}-dashboard-dark-safearea.png`,fullPage:true})
  await page.getByRole('button',{name:'关闭联系方式'}).click();await expect(panel).toBeHidden()
  await page.goto('/appearance');await expect(page.getByRole('heading',{name:'登录页轮播图'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBeTruthy()
  expect(errors).toEqual([])
})
