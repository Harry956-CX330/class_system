  await dialog.getByRole('button',{name:'取消',exact:true}).click()
  await page.goto('/notices');await page.getByRole('button',{name:'发布新通知'}).click()
  dialog=page.getByRole('dialog')
  const title=`多图分类-${info.project.name}`
  await dialog.getByPlaceholder('请输入通知标题，建议言简意赅').fill(title)
  await dialog.getByRole('textbox',{name:'富文本正文'}).fill('两张图片的通知')
